/** Language of the interface for the browser, the first of its preferred languages that has labels, or English. */
function browserLanguage() {
    return navigator.languages.map((lang) => lang.split("-")[0].toLowerCase()).find((language) => Object.hasOwn(labels, language)) ?? "en";
}

